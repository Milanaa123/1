"""Evidence-based Russian vernacular names and safe family recovery.

The CoL source lineage is authoritative for its taxonomy. A missing family can
be filled from the same *uniquely classified* genus, never by an animal's
appearance or only its order. Russian common names are exact scientific-name
matches from a curated small dictionary and the pinned BirdNET+ metadata CSV.
Unknown names are not translated automatically or mislabelled as official.
"""
import csv, hashlib, io, json, re, urllib.request
from pathlib import Path

_DATA=json.loads((Path(__file__).resolve().parent/'ru_taxonomy.json').read_text(encoding='utf-8'))
SPECIES_RU=_DATA['species_ru']
FAMILY_RU=_DATA['family_ru']
EXTERNAL_SPECIES_RU={}
EXTERNAL_STATS={}
_RUSSIAN_BULK_JSON=(Path(__file__).resolve().parent/'russian_vernacular_snapshot.json')
RUSSIAN_SNAPSHOT=json.loads(_RUSSIAN_BULK_JSON.read_text(encoding='utf-8'))
assert RUSSIAN_SNAPSHOT['source']=='taxadb 2026, exact accepted Russian vernacular names'
BULK_NAMES=RUSSIAN_SNAPSHOT['names']
_WIKIDATA_RU_JSON=(Path(__file__).resolve().parent/'russian_wikidata_snapshot.json')
WIKIDATA_SNAPSHOT=json.loads(_WIKIDATA_RU_JSON.read_text(encoding='utf-8'))
assert WIKIDATA_SNAPSHOT['source']=='Wikidata CC0 species rank Q7432; Russian language labels'
WIKIDATA_NAMES=WIKIDATA_SNAPSHOT['names']
assert len(WIKIDATA_NAMES)==WIKIDATA_SNAPSHOT['count']
assert len(BULK_NAMES)==RUSSIAN_SNAPSHOT['count'] and len(BULK_NAMES)>10000
# Official iNaturalist Russian vernacular export; generated by an audited
# workflow. Optional until the first successful source import.
_INAT_PATH=Path(__file__).resolve().parent/'russian_inaturalist_snapshot.json'
INAT_SNAPSHOT=json.loads(_INAT_PATH.read_text(encoding='utf-8')) if _INAT_PATH.exists() else {'count':0,'names':{}}
assert INAT_SNAPSHOT['count']==len(INAT_SNAPSHOT['names'])
if INAT_SNAPSHOT['count']:
    assert INAT_SNAPSHOT['source']=='iNaturalist official taxonomy DarwinCore Archive, Russian lexicon'
INAT_NAMES=INAT_SNAPSHOT['names']
_BVI_PATH=Path(__file__).resolve().parent/'russian_bvi_snapshot.json'
BVI_SNAPSHOT=json.loads(_BVI_PATH.read_text(encoding='utf-8')) if _BVI_PATH.exists() else {'count':0,'names':{}}
assert BVI_SNAPSHOT['count']==len(BVI_SNAPSHOT['names'])
if BVI_SNAPSHOT['count']:
    assert BVI_SNAPSHOT['source']=='BVI historical taxonomy index: real Russian animal names'
BVI_NAMES=BVI_SNAPSHOT['names']

BIRDNET_URL='https://birdnet.cornell.edu/taxonomy/api/download/csv'
BIRDNET_SHA256='daecb2505ff16dddbafe76cfa8d15a044c506b6a2998b2349a94bcd355475ac4'
_RUSSIAN=re.compile(r'^[А-ЯЁа-яё][А-ЯЁа-яё\s\-–—()«».,\x27’]+$')
_CANONICAL=re.compile(r'^[A-Z][a-z-]+ [a-z-]+$')

def load_birdnet_names():
    """Pin the exact open-MIT dataset to avoid silent taxonomy drift."""
    global EXTERNAL_STATS
    request=urllib.request.Request(BIRDNET_URL,headers={'User-Agent':'Animagia-catalogue-builder/1.0'})
    with urllib.request.urlopen(request,timeout=70) as response:
        content=response.read(24_000_001)
    if len(content)>24_000_000:
        raise ValueError('BirdNET+ names source exceeds expected size')
    sha=hashlib.sha256(content).hexdigest()
    if sha!=BIRDNET_SHA256:
        raise ValueError('BirdNET+ source was changed; review names before publishing: '+sha)
    reader=csv.DictReader(io.StringIO(content.decode('utf-8-sig',errors='strict')))
    required={'scientific_name','common_name_ru','record_type'}
    if not required.issubset(reader.fieldnames or []):
        raise ValueError('BirdNET+ species name columns absent')
    unique={}
    conflicts=set()
    examined=0
    for item in reader:
        examined+=1
        if item.get('record_type')!='species':
            continue
        name=item.get('scientific_name','').strip()
        russian=item.get('common_name_ru','').strip()
        if not _CANONICAL.fullmatch(name) or len(russian)>130 or not _RUSSIAN.fullmatch(russian):
            continue
        if name in unique and unique[name]!=russian:
            conflicts.add(name)
        else:
            unique[name]=russian
    for name in conflicts:
        unique.pop(name,None)
    EXTERNAL_SPECIES_RU.clear()
    EXTERNAL_SPECIES_RU.update(unique)
    EXTERNAL_STATS.clear()
    EXTERNAL_STATS.update({'source':'BirdNET+ Taxonomy v0.4-Oct2026',
      'source_url':BIRDNET_URL,'sha256':sha,'source_rows':examined,
      'russian_name_candidates':len(unique),'ambiguous_names_rejected':len(conflicts)})
    return EXTERNAL_STATS

def source_vernacular_name(scientific, family, animal_class, order, phylum, rank):
    """Use a real Russian vernacular only for a matching accepted taxon."""
    if not all(isinstance(v,str) for v in (scientific,family,animal_class,order,phylum,rank)):
        return ''
    if not animal_class or not phylum or rank not in ('species','subspecies'):
        return ''
    data=BULK_NAMES.get(scientific.casefold()+'|'+rank)
    if not data or len(data)!=6:
        return ''
    name,source,src_phylum,src_class,src_order,src_family=data
    if source not in ('col','gbif','itis','ncbi'):
        return ''
    for site_value,source_value in ((phylum,src_phylum),(animal_class,src_class),
                                    (order,src_order),(family,src_family)):
        if site_value and source_value and site_value!=source_value:
            return ''
    return name if _RUSSIAN.fullmatch(name) else ''

def inat_ru_label(scientific, family, animal_class, order, phylum, rank):
    """iNaturalist official Russian lexicon; exact rank/name and compatible taxa."""
    if rank not in ('species','subspecies') or not isinstance(scientific,str):
        return ''
    data=INAT_NAMES.get(scientific.casefold()+'|'+rank)
    if not data or len(data)!=6:return ''
    label,src_phylum,src_class,src_order,src_family,inat_id=data
    if not str(inat_id).isdecimal():return ''
    for ours,theirs in ((phylum,src_phylum),(animal_class,src_class),
                        (order,src_order),(family,src_family)):
        if ours and theirs and ours!=theirs:return ''
    return label if _RUSSIAN.fullmatch(label) else ''

def bvi_ru_label(scientific,animal_class,rank):
    """Published Russian zoological names matching the exact class and binomial."""
    if not isinstance(scientific,str) or not animal_class or rank not in ('species','subspecies'):
        return ''
    entry=BVI_NAMES.get(scientific.casefold()+'|'+rank)
    if not entry or len(entry)!=3:return ''
    label,classes,source_url=entry
    if animal_class not in classes or not source_url.startswith('https://bvi.rusf.ru/'):
        return ''
    return label if _RUSSIAN.fullmatch(label) else ''

def wikidata_ru_label(scientific,rank):
    """Wikidata CC0 community-curated species label for exact scientific binomial."""
    if rank!='species' or not isinstance(scientific,str):
        return ''
    entry=WIKIDATA_NAMES.get(scientific.casefold())
    if not entry or len(entry)!=2:
        return ''
    label,qid=entry
    if not re.fullmatch(r'Q[0-9]{1,11}',qid):
        return ''
    return label if _RUSSIAN.fullmatch(label) else ''

def taxon_ru_labels(scientific, family, animal_class='', order='', phylum='', rank='species'):
    common=SPECIES_RU.get(scientific, '') or EXTERNAL_SPECIES_RU.get(scientific, '')
    if not common:
        common=source_vernacular_name(scientific,family,animal_class,order,phylum,rank)
    if not common and animal_class and phylum:
        common=inat_ru_label(scientific,family,animal_class,order,phylum,rank)
    if not common and animal_class and phylum:
        common=bvi_ru_label(scientific,animal_class,rank)
    if not common and animal_class and phylum:
        common=wikidata_ru_label(scientific,rank)
    return FAMILY_RU.get(family, ''),common

def indexed_taxon_row(score, scientific, rank, lineage):
    family=lineage.get('family','').strip()
    family_ru, common_ru=taxon_ru_labels(scientific, family,lineage.get('class',''),lineage.get('order',''),lineage.get('phylum',''),rank)
    # Do not assign a species name to subspecies merely because they share a binomial.
    return [score,scientific,rank,lineage.get('class',''),
            lineage.get('order',''),'',lineage.get('phylum',''),
            family,family_ru,common_ru]

def genus_key(phylum, animal_class, order, scientific):
    return (phylum,animal_class,order,scientific.split(' ',1)[0])

def family_from_unambiguous_genus(lineage_families, row):
    if row[7]:
        return ''
    candidates=lineage_families.get(genus_key(row[6],row[3],row[4],row[1]),set())
    if len(candidates)==1:
        return next(iter(candidates))
    return ''
